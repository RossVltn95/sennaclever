    /**
     * Build Comparable Transactions sheet
     */
    private function build_comparables_sheet($spreadsheet, $post, $deal_financials) {
        $sheet = $spreadsheet->createSheet();
        $sheet->setTitle('Comparable Analysis');

        // Set column widths
        $sheet->getColumnDimension('A')->setWidth(25);
        $sheet->getColumnDimension('B')->setWidth(20);
        $sheet->getColumnDimension('C')->setWidth(12);
        $sheet->getColumnDimension('D')->setWidth(12);
        $sheet->getColumnDimension('E')->setWidth(12);
        $sheet->getColumnDimension('F')->setWidth(12);

        // Header
        $sheet->setCellValue('A1', 'COMPARABLE TRANSACTIONS');
        $sheet->mergeCells('A1:F1');
        $this->style_header($sheet, 'A1:F1');

        $row = 3;

        // Current Deal Reference
        $sheet->setCellValue('A' . $row, 'CURRENT TRANSACTION');
        $this->style_section_header($sheet, 'A' . $row);
        $row++;

        $sheet->setCellValue('A' . $row, 'Target');
        $sheet->setCellValue('B' . $row, 'Buyer');
        $sheet->setCellValue('C' . $row, 'Date');
        $sheet->setCellValue('D' . $row, 'EV');
        $sheet->setCellValue('E' . $row, 'EV/EBITDA');
        $sheet->setCellValue('F' . $row, 'EV/Rev');
        $this->style_table_header($sheet, 'A' . $row . ':F' . $row);
        $row++;

        // Current deal
        $target_name = '';
        if (!empty($deal_financials['companies_involved'])) {
            $companies = $deal_financials['companies_involved'];
            $target_name = is_array($companies) ? ($companies[0] ?? 'Target') : $companies;
        }

        $buyer_name = $deal_financials['buyer']['name'] ?? $deal_financials['pe_firm'] ?? 'Buyer';

        $sheet->setCellValue('A' . $row, $target_name);
        $sheet->setCellValue('B' . $row, $buyer_name);
        $sheet->setCellValue('C' . $row, date('M Y'));
        $sheet->setCellValue('D' . $row, $deal_financials['deal_value']['formatted'] ?? 'N/A');
        $sheet->setCellValue('E' . $row, !empty($deal_financials['multiples']['ev_ebitda']['value']) ? number_format($deal_financials['multiples']['ev_ebitda']['value'], 1) . 'x' : 'N/A');
