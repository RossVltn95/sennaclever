                ),
            ),
        ));
    }

    /**
     * Format currency value
     */
    private function format_currency($amount, $currency = 'USD') {
        $symbols = array(
            'USD' => '$',
            'GBP' => '£',
            'EUR' => '€',
            'JPY' => '¥',
        );

        $symbol = $symbols[$currency] ?? $currency . ' ';

        if ($amount >= 1000000000) {
            return $symbol . number_format($amount / 1000000000, 2) . 'bn';
        } elseif ($amount >= 1000000) {
            return $symbol . number_format($amount / 1000000, 1) . 'm';
        } elseif ($amount >= 1000) {
            return $symbol . number_format($amount / 1000, 1) . 'k';
        }

        return $symbol . number_format($amount, 0);
    }

    /**
     * Get human-readable source label
     */
    private function get_source_label($source) {
        $labels = array(
            'disclosed' => 'Disclosed',
            'calculated' => 'Calculated',
            'estimated' => 'Estimated',
            'unknown' => 'Unknown',
        );

        return $labels[strtolower($source)] ?? ucfirst($source);
    }

    /**
     * Generate unique filename
     */
    private function generate_filename($post) {
        $title = sanitize_file_name($post->post_title);
        $title = substr($title, 0, 50); // Limit length
        $timestamp = date('Ymd_His');
        $random = substr(md5(uniqid()), 0, 6);

        return sprintf('Deal_Model_%s_%s_%s.xlsx', $title, $timestamp, $random);
    }

    /**
     * Create secure download URL
     */
    private function create_download_url($filename, $post_id) {
        $nonce = wp_create_nonce('download_deal_model_' . $filename);

        return add_query_arg(array(
            'action' => 'sffc_download_deal_model',
            'file' => $filename,
            'post_id' => $post_id,
            'nonce' => $nonce,
        ), admin_url('admin-ajax.php'));
    }

    /**
     * Track download for analytics
     */
    private function track_download($post_id) {
        $downloads = get_post_meta($post_id, '_sffc_model_downloads', true);
        $downloads = is_numeric($downloads) ? (int) $downloads : 0;
        update_post_meta($post_id, '_sffc_model_downloads', $downloads + 1);
        update_post_meta($post_id, '_sffc_last_model_download', current_time('mysql'));
    }

    /**
     * Handle file download (static method for AJAX)
     */
    public static function handle_download() {
        // Verify nonce
        if (!isset($_GET['nonce']) || !isset($_GET['file'])) {
            wp_die('Invalid request');
        }

        $filename = sanitize_file_name($_GET['file']);

        if (!wp_verify_nonce($_GET['nonce'], 'download_deal_model_' . $filename)) {
            wp_die('Security check failed');
        }

        // Build file path
        $filepath = plugin_dir_path(dirname(__FILE__)) . 'exports/generated/' . $filename;

        if (!file_exists($filepath)) {
            wp_die('File not found');
        }

        // Send download headers
        header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
        header('Content-Disposition: attachment; filename="' . basename($filename) . '"');
        header('Content-Length: ' . filesize($filepath));
        header('Cache-Control: private, no-cache, no-store, must-revalidate');
        header('Pragma: no-cache');
        header('Expires: 0');

        // Output file
        readfile($filepath);
        exit;
    }

    /**
     * Clean up old generated files
     */
    public function cleanup_old_files($max_age_hours = 24) {
        $files = glob($this->generated_dir . 'Deal_Model_*.xlsx');
        $cutoff = time() - ($max_age_hours * 3600);

        foreach ($files as $file) {
            if (filemtime($file) < $cutoff) {
                unlink($file);
            }
        }
    }
}

