            if (!empty($financials['ebitda_growth'])) {
                $sheet->setCellValue('A' . $row, 'EBITDA Growth');
                $sheet->setCellValue('B' . $row, number_format($financials['ebitda_growth'], 1) . '%');
                $sheet->setCellValue('C' . $row, $this->get_source_label($financials['ebitda_growth_source'] ?? 'estimated'));
                $row++;
            }
