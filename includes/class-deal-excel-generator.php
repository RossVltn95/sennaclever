    /**
     * Build Sensitivity Analysis sheet
     */
    private function build_sensitivity_sheet($spreadsheet, $post, $deal_financials) {
        $sheet = $spreadsheet->createSheet();
        $sheet->setTitle('Sensitivity Analysis');

        // Set column widths
        for ($col = 'A'; $col <= 'G'; $col++) {
            $sheet->getColumnDimension($col)->setWidth(12);
        }
        $sheet->getColumnDimension('A')->setWidth(18);

        // Header
        $sheet->setCellValue('A1', 'SENSITIVITY ANALYSIS');
        $sheet->mergeCells('A1:G1');
        $this->style_header($sheet, 'A1:G1');

        $row = 3;

        // Get base case values
        $scenarios = $deal_financials['ai_enhanced']['scenarios'] ?? $deal_financials['scenarios'] ?? array();
        $base_irr = $scenarios['base']['irr'] ?? 15;
        $entry_multiple = $deal_financials['multiples']['ev_ebitda']['value'] ?? $deal_financials['multiples']['ev_operating_profit']['value'] ?? 12;
        $base_exit = $scenarios['base']['exit_multiple'] ?? 14;

        // IRR Sensitivity Table: Exit Multiple vs Hold Period
        $sheet->setCellValue('A' . $row, 'IRR SENSITIVITY: Exit Multiple vs Hold Period');
        $this->style_section_header($sheet, 'A' . $row);
        $row++;

        // Create sensitivity matrix
        $exit_multiples = array(
            round($base_exit * 0.7, 1),
            round($base_exit * 0.85, 1),
            round($base_exit, 1),
            round($base_exit * 1.15, 1),
            round($base_exit * 1.3, 1)
        );
        $hold_periods = array(3, 4, 5, 6, 7);

        // Header row
        $sheet->setCellValue('A' . $row, 'Exit Multiple / Years');
        $col = 'B';
        foreach ($hold_periods as $years) {
            $sheet->setCellValue($col . $row, $years . ' Years');
            $col++;
        }
        $this->style_table_header($sheet, 'A' . $row . ':F' . $row);
        $row++;

        // Calculate IRR for each combination
        foreach ($exit_multiples as $exit) {
            $sheet->setCellValue('A' . $row, $exit . 'x');
            $sheet->getStyle('A' . $row)->getFont()->setBold(true);

            $col = 'B';
            foreach ($hold_periods as $years) {
                // Simple IRR approximation: IRR = (Exit/Entry)^(1/n) - 1
                $irr = (pow($exit / $entry_multiple, 1 / $years) - 1) * 100;
                $sheet->setCellValue($col . $row, number_format($irr, 1) . '%');

                // Color code
                if ($irr >= 20) {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFD1FAE5');
                    $sheet->getStyle($col . $row)->getFont()->setColor(new Color('047857'));
                } elseif ($irr >= 12) {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEF3C7');
                    $sheet->getStyle($col . $row)->getFont()->setColor(new Color('92400E'));
                } else {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEE2E2');
                    $sheet->getStyle($col . $row)->getFont()->setColor(new Color('991B1B'));
                }

                $col++;
            }
            $row++;
        }

        $row += 2;

        // MOIC Sensitivity Table
        $sheet->setCellValue('A' . $row, 'MOIC SENSITIVITY: Exit Multiple vs Hold Period');
        $this->style_section_header($sheet, 'A' . $row);
        $row++;

        // Header row
        $sheet->setCellValue('A' . $row, 'Exit Multiple / Years');
        $col = 'B';
        foreach ($hold_periods as $years) {
            $sheet->setCellValue($col . $row, $years . ' Years');
            $col++;
        }
        $this->style_table_header($sheet, 'A' . $row . ':F' . $row);
        $row++;

        // Calculate MOIC for each combination
        foreach ($exit_multiples as $exit) {
            $sheet->setCellValue('A' . $row, $exit . 'x');
            $sheet->getStyle('A' . $row)->getFont()->setBold(true);

            $col = 'B';
            foreach ($hold_periods as $years) {
                // MOIC = Exit Multiple / Entry Multiple
                $moic = $exit / $entry_multiple;
                $sheet->setCellValue($col . $row, number_format($moic, 2) . 'x');

                // Color code
                if ($moic >= 2.5) {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFD1FAE5');
                } elseif ($moic >= 1.5) {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEF3C7');
                } else {
                    $sheet->getStyle($col . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEE2E2');
                }

                $col++;
            }
            $row++;
        }

        $row += 2;

        // Legend
        $sheet->setCellValue('A' . $row, 'Legend:');
        $sheet->getStyle('A' . $row)->getFont()->setBold(true);
        $row++;

        $sheet->setCellValue('A' . $row, 'Attractive (IRR >= 20% / MOIC >= 2.5x)');
        $sheet->getStyle('A' . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFD1FAE5');
        $row++;

        $sheet->setCellValue('A' . $row, 'Moderate (IRR 12-20% / MOIC 1.5-2.5x)');
        $sheet->getStyle('A' . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEF3C7');
        $row++;

        $sheet->setCellValue('A' . $row, 'Challenging (IRR < 12% / MOIC < 1.5x)');
        $sheet->getStyle('A' . $row)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setARGB('FFFEE2E2');

        // Apply borders
        $this->apply_borders($sheet, 'A3:F' . $row);
    }

