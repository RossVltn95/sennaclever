if (!class_exists('SFFC_Deal_Excel_Generator')) {

class SFFC_Deal_Excel_Generator {

    /**
     * Export directory path
     */
    private $export_dir;

    /**
     * Generated files directory
     */
    private $generated_dir;

    /**
     * Brand colors
     */
    private $colors = array(
        'navy'       => '132D51',
        'green'      => '2D6A4F',
        'light_blue' => 'E8F4FD',
        'light_green'=> 'E8F5E9',
        'gray'       => 'F5F5F5',
        'border'     => 'D1D5DB',
        'text'       => '374151',
        'muted'      => '6B7280',
        'positive'   => '059669',
        'negative'   => 'DC2626',
        'warning'    => 'D97706',
    );

    /**
     * Constructor
     */
    public function __construct() {
        $this->export_dir = plugin_dir_path(dirname(__FILE__)) . 'exports/';
        $this->generated_dir = $this->export_dir . 'generated/';

        $this->ensure_directories();
    }

    /**
     * Ensure export directories exist
     */
    private function ensure_directories() {
        $dirs = array($this->export_dir, $this->generated_dir);

        foreach ($dirs as $dir) {
            if (!file_exists($dir)) {
                wp_mkdir_p($dir);
            }
        }
    }

    /**
     * Generate Excel model for a deal article
     *
     * @param int $post_id Post ID of the deal article
     * @return array Result with success status and download URL
     */
    public function generate($post_id) {
        try {
            // Check if libraries are loaded
            if (!defined('SFFC_LIBRARIES_LOADED') || !SFFC_LIBRARIES_LOADED) {
                throw new Exception('Export libraries not installed.');
            }

            // Check if PhpSpreadsheet is available
            if (!class_exists('PhpOffice\PhpSpreadsheet\Spreadsheet')) {
                throw new Exception('PhpSpreadsheet library not found.');
            }

            // Get post data
            $post = get_post($post_id);
            if (!$post) {
                throw new Exception('Article not found.');
            }

            // Get deal financials meta
            $deal_financials = get_post_meta($post_id, '_sffc_deal_financials', true);
            if (empty($deal_financials)) {
                throw new Exception('No deal financials available for this article.');
            }

            // Create spreadsheet
            $spreadsheet = new Spreadsheet();

            // Set document properties
            $spreadsheet->getProperties()
                ->setCreator('MENA Careers')
                ->setLastModifiedBy('MENA Careers')
                ->setTitle('Deal Analysis - ' . $post->post_title)
                ->setSubject('Financial Model')
                ->setDescription('Investment analysis model generated by MENA Careers')
                ->setKeywords('deal analysis financial model PE')
                ->setCategory('Financial Analysis');

            // Build sheets
            $this->build_summary_sheet($spreadsheet, $post, $deal_financials);
            $this->build_transaction_sheet($spreadsheet, $post, $deal_financials);
            $this->build_financials_sheet($spreadsheet, $post, $deal_financials);
            $this->build_comparables_sheet($spreadsheet, $post, $deal_financials);
            $this->build_scenario_sheet($spreadsheet, $post, $deal_financials);
            $this->build_sensitivity_sheet($spreadsheet, $post, $deal_financials);
            $this->build_risks_sheet($spreadsheet, $post, $deal_financials);
            $this->build_sources_sheet($spreadsheet, $post, $deal_financials);

            // Set active sheet to Summary
            $spreadsheet->setActiveSheetIndex(0);

            // Generate filename
            $filename = $this->generate_filename($post);
            $filepath = $this->generated_dir . $filename;

            // Save file
            $writer = new Xlsx($spreadsheet);
            $writer->save($filepath);

            // Generate download URL
            $download_url = $this->create_download_url($filename, $post_id);

            // Track download
            $this->track_download($post_id);

            return array(
                'success' => true,
                'filename' => $filename,
                'filepath' => $filepath,
                'download_url' => $download_url,
                'format' => 'xlsx'
            );

        } catch (Exception $e) {
            error_log('Deal Excel Generator Error: ' . $e->getMessage());
            return array(
                'success' => false,
                'message' => $e->getMessage()
            );
        }
    }

    /**
     * Build Executive Summary sheet
     */
    private function build_summary_sheet($spreadsheet, $post, $deal_financials) {
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Executive Summary');

        // Set column widths
        $sheet->getColumnDimension('A')->setWidth(25);
        $sheet->getColumnDimension('B')->setWidth(20);
        $sheet->getColumnDimension('C')->setWidth(20);
        $sheet->getColumnDimension('D')->setWidth(15);
        $sheet->getColumnDimension('E')->setWidth(15);

        // Header
        $sheet->setCellValue('A1', 'DEAL ANALYSIS');
        $sheet->mergeCells('A1:E1');
        $this->style_header($sheet, 'A1:E1');

        // Deal title
        $sheet->setCellValue('A3', $post->post_title);
        $sheet->mergeCells('A3:E3');
        $sheet->getStyle('A3')->getFont()->setBold(true)->setSize(14);

        // Date
        $sheet->setCellValue('A4', 'Analysis Date: ' . date('F j, Y'));
        $sheet->getStyle('A4')->getFont()->setColor(new Color($this->colors['muted']));

        // Key Metrics Section
        $sheet->setCellValue('A6', 'KEY METRICS');
        $this->style_section_header($sheet, 'A6');

        $row = 7;

        // Deal Value
        if (!empty($deal_financials['deal_value'])) {
            $sheet->setCellValue('A' . $row, 'Deal Value');
            $sheet->setCellValue('B' . $row, $deal_financials['deal_value']['formatted'] ?? $this->format_currency($deal_financials['deal_value']['amount'] ?? 0, $deal_financials['deal_value']['currency'] ?? 'USD'));
            $sheet->setCellValue('C' . $row, $this->get_source_label($deal_financials['deal_value']['source'] ?? 'unknown'));
            $row++;
        }

        // Net Proceeds
        if (!empty($deal_financials['net_proceeds']['amount'])) {
            $sheet->setCellValue('A' . $row, 'Net Proceeds');
            $sheet->setCellValue('B' . $row, $deal_financials['net_proceeds']['formatted'] ?? $this->format_currency($deal_financials['net_proceeds']['amount'], $deal_financials['net_proceeds']['currency'] ?? 'USD'));
            $sheet->setCellValue('C' . $row, $this->get_source_label($deal_financials['net_proceeds']['source'] ?? 'unknown'));
            $row++;
        }

        // Deal Type
        if (!empty($deal_financials['deal_type'])) {
            $sheet->setCellValue('A' . $row, 'Deal Type');
            $sheet->setCellValue('B' . $row, ucfirst($deal_financials['deal_type']));
            $row++;
        }

        // Sector
        if (!empty($deal_financials['sector'])) {
            $sheet->setCellValue('A' . $row, 'Sector');
            $sheet->setCellValue('B' . $row, $deal_financials['sector']);
            $row++;
        }

        // Region
        if (!empty($deal_financials['region'])) {
            $sheet->setCellValue('A' . $row, 'Region');
            $sheet->setCellValue('B' . $row, $deal_financials['region']);
            $row++;
        }

        $row++;

        // Multiples Section
        if (!empty($deal_financials['multiples'])) {
            $sheet->setCellValue('A' . $row, 'VALUATION MULTIPLES');
            $this->style_section_header($sheet, 'A' . $row);
            $row++;

            $multiples = $deal_financials['multiples'];

            if (!empty($multiples['ev_revenue']['value'])) {
                $sheet->setCellValue('A' . $row, 'EV / Revenue');
                $sheet->setCellValue('B' . $row, number_format($multiples['ev_revenue']['value'], 1) . 'x');
                $sheet->setCellValue('C' . $row, $this->get_source_label($multiples['ev_revenue']['source'] ?? 'unknown'));
                $row++;
            }

            if (!empty($multiples['ev_ebitda']['value'])) {
                $sheet->setCellValue('A' . $row, 'EV / EBITDA');
                $sheet->setCellValue('B' . $row, number_format($multiples['ev_ebitda']['value'], 1) . 'x');
                $sheet->setCellValue('C' . $row, $this->get_source_label($multiples['ev_ebitda']['source'] ?? 'unknown'));
                $row++;
            }

            if (!empty($multiples['ev_operating_profit']['value'])) {
                $sheet->setCellValue('A' . $row, 'EV / Operating Profit');
                $sheet->setCellValue('B' . $row, number_format($multiples['ev_operating_profit']['value'], 1) . 'x');
                $sheet->setCellValue('C' . $row, $this->get_source_label($multiples['ev_operating_profit']['source'] ?? 'unknown'));
                $row++;
            }

            if (!empty($multiples['ev_net_income']['value'])) {
                $sheet->setCellValue('A' . $row, 'EV / Net Income');
                $sheet->setCellValue('B' . $row, number_format($multiples['ev_net_income']['value'], 1) . 'x');
                $sheet->setCellValue('C' . $row, $this->get_source_label($multiples['ev_net_income']['source'] ?? 'unknown'));
                $row++;
            }
        }

        $row++;

        // Scenario Summary
        if (!empty($deal_financials['ai_enhanced']['scenarios'])) {
            $sheet->setCellValue('A' . $row, 'SCENARIO SUMMARY');
            $this->style_section_header($sheet, 'A' . $row);
            $row++;

            // Headers
            $sheet->setCellValue('A' . $row, 'Scenario');
            $sheet->setCellValue('B' . $row, 'IRR');
            $sheet->setCellValue('C' . $row, 'MOIC');
            $sheet->setCellValue('D' . $row, 'Exit Year');
            $this->style_table_header($sheet, 'A' . $row . ':D' . $row);
            $row++;

            $scenarios = $deal_financials['ai_enhanced']['scenarios'];

            foreach (array('base', 'upside', 'downside') as $type) {
                if (!empty($scenarios[$type])) {
                    $scenario = $scenarios[$type];
                    $sheet->setCellValue('A' . $row, ucfirst($type) . ' Case');
                    $sheet->setCellValue('B' . $row, ($scenario['irr'] ?? 0) . '%');
                    $sheet->setCellValue('C' . $row, ($scenario['moic'] ?? 0) . 'x');
                    $sheet->setCellValue('D' . $row, 'Year ' . ($scenario['exit_year'] ?? 5));

                    // Color code by scenario type
                    $color = $type === 'upside' ? $this->colors['positive'] : ($type === 'downside' ? $this->colors['negative'] : $this->colors['text']);
                    $sheet->getStyle('B' . $row)->getFont()->setColor(new Color($color));
                    $row++;
                }
            }
        }

        $row += 2;

        // Data Quality
        if (!empty($deal_financials['data_quality'])) {
            $sheet->setCellValue('A' . $row, 'DATA QUALITY ASSESSMENT');
            $this->style_section_header($sheet, 'A' . $row);
            $row++;

            $dq = $deal_financials['data_quality'];

            $sheet->setCellValue('A' . $row, 'Overall Score');
            $sheet->setCellValue('B' . $row, ($dq['overall_score'] ?? 0) . '%');
            $row++;

            $sheet->setCellValue('A' . $row, 'Disclosed Metrics');
            $sheet->setCellValue('B' . $row, $dq['disclosed_count'] ?? 0);
            $row++;

            $sheet->setCellValue('A' . $row, 'Calculated Metrics');
            $sheet->setCellValue('B' . $row, $dq['calculated_count'] ?? 0);
            $row++;

            $sheet->setCellValue('A' . $row, 'Estimated Metrics');
            $sheet->setCellValue('B' . $row, $dq['estimated_count'] ?? 0);
            $row++;
        }

        // Apply borders to data area
        $this->apply_borders($sheet, 'A6:D' . $row);
    }

    /**
     * Build Transaction Details sheet
     */
    private function build_transaction_sheet($spreadsheet, $post, $deal_financials) {
        $sheet = $spreadsheet->createSheet();
        $sheet->setTitle('Transaction Details');

        // Set column widths
        $sheet->getColumnDimension('A')->setWidth(25);
        $sheet->getColumnDimension('B')->setWidth(30);
        $sheet->getColumnDimension('C')->setWidth(15);

        // Header
        $sheet->setCellValue('A1', 'TRANSACTION DETAILS');
        $sheet->mergeCells('A1:C1');
        $this->style_header($sheet, 'A1:C1');

        $row = 3;

        // Deal Information
        $sheet->setCellValue('A' . $row, 'DEAL INFORMATION');
        $this->style_section_header($sheet, 'A' . $row);
        $row++;

        // Headers
        $sheet->setCellValue('A' . $row, 'Item');
        $sheet->setCellValue('B' . $row, 'Value');
        $sheet->setCellValue('C' . $row, 'Source');
        $this->style_table_header($sheet, 'A' . $row . ':C' . $row);
        $row++;

        // Deal Value
        $sheet->setCellValue('A' . $row, 'Enterprise Value');
        $sheet->setCellValue('B' . $row, $deal_financials['deal_value']['formatted'] ?? 'N/A');
        $sheet->setCellValue('C' . $row, $this->get_source_label($deal_financials['deal_value']['source'] ?? 'unknown'));
        $row++;

        // Net Proceeds
        if (!empty($deal_financials['net_proceeds']['amount'])) {
            $sheet->setCellValue('A' . $row, 'Net Proceeds');
            $sheet->setCellValue('B' . $row, $deal_financials['net_proceeds']['formatted'] ?? 'N/A');
            $sheet->setCellValue('C' . $row, $this->get_source_label($deal_financials['net_proceeds']['source'] ?? 'unknown'));
            $row++;
        }

        // Deal Type
        $sheet->setCellValue('A' . $row, 'Transaction Type');
        $sheet->setCellValue('B' . $row, ucfirst($deal_financials['deal_type'] ?? 'Unknown'));
        $row++;

        // Deal Stage
        if (!empty($deal_financials['deal_stage'])) {
            $sheet->setCellValue('A' . $row, 'Deal Stage');
            $sheet->setCellValue('B' . $row, ucfirst($deal_financials['deal_stage']));
            $row++;
        }

        $row++;

        // Buyer Information
        if (!empty($deal_financials['buyer'])) {
            $sheet->setCellValue('A' . $row, 'BUYER INFORMATION');
            $this->style_section_header($sheet, 'A' . $row);
            $row++;

            $buyer = $deal_financials['buyer'];

            $sheet->setCellValue('A' . $row, 'Buyer Name');
            $sheet->setCellValue('B' . $row, $buyer['name'] ?? 'N/A');
            $row++;

            if (!empty($buyer['type'])) {
                $sheet->setCellValue('A' . $row, 'Buyer Type');
                $sheet->setCellValue('B' . $row, ucfirst(str_replace('_', ' ', $buyer['type'])));
                $row++;
            }

            if (!empty($buyer['typical_hold_period'])) {
                $sheet->setCellValue('A' . $row, 'Typical Hold Period');
                $sheet->setCellValue('B' . $row, $buyer['typical_hold_period']);
                $row++;
            }
        }

        $row++;

        // Seller Information
        if (!empty($deal_financials['seller'])) {
            $sheet->setCellValue('A' . $row, 'SELLER INFORMATION');
            $this->style_section_header($sheet, 'A' . $row);
            $row++;

            $seller = $deal_financials['seller'];

            $sheet->setCellValue('A' . $row, 'Seller Name');
            $sheet->setCellValue('B' . $row, $seller['name'] ?? 'N/A');
            $row++;

            if (!empty($seller['ticker'])) {
                $sheet->setCellValue('A' . $row, 'Ticker');
                $sheet->setCellValue('B' . $row, $seller['ticker']);
                $row++;
            }

            if (!empty($seller['stock_impact'])) {
                $sheet->setCellValue('A' . $row, 'Stock Impact');
                $sheet->setCellValue('B' . $row, $seller['stock_impact']);
                $row++;
            }
        }

        // Apply borders
        $this->apply_borders($sheet, 'A3:C' . $row);
    }

