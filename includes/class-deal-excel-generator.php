        // Set row height
        $row = substr($range, strpos($range, ':') !== false ? 1 : 1);
        $row = preg_replace('/[^0-9]/', '', $row);
        $sheet->getRowDimension($row)->setRowHeight(30);
    }

    /**
     * Style section header
     */
    private function style_section_header($sheet, $cell) {
        $sheet->getStyle($cell)->applyFromArray(array(
            'font' => array(
                'bold' => true,
